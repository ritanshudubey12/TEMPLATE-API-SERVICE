CREATE TABLE templates (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  scope TEXT NOT NULL CHECK (scope IN ('PLATFORM','TENANT','ORGANIZATION')),
  tenant_id BIGINT NULL,
  organization_id BIGINT NULL,
  slug TEXT NOT NULL,
  name TEXT NOT NULL,
  description TEXT,
  category_id BIGINT REFERENCES template_categories(id),
  visibility TEXT NOT NULL DEFAULT 'PRIVATE'
    CHECK (visibility IN ('PRIVATE','TENANT','ORGANIZATION','PUBLIC')),
  status TEXT NOT NULL DEFAULT 'DRAFT'
    CHECK (status IN ('DRAFT','PUBLISHED','ARCHIVED')),
  current_published_version_id BIGINT NULL,
  created_by BIGINT NOT NULL,
  updated_by BIGINT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  deleted_at TIMESTAMPTZ,
  CHECK (scope <> 'ORGANIZATION' OR (organization_id IS NOT NULL AND tenant_id IS NOT NULL)),
  CHECK (scope <> 'TENANT' OR tenant_id IS NOT NULL),
  CHECK (scope <> 'PLATFORM' OR (tenant_id IS NULL AND organization_id IS NULL))
);

-- Scope-aware slug uniqueness
CREATE UNIQUE INDEX ux_templates_slug_platform
  ON templates (slug) WHERE scope = 'PLATFORM' AND deleted_at IS NULL;
CREATE UNIQUE INDEX ux_templates_slug_tenant
  ON templates (tenant_id, slug) WHERE scope = 'TENANT' AND deleted_at IS NULL;
CREATE UNIQUE INDEX ux_templates_slug_org
  ON templates (tenant_id, organization_id, slug) WHERE scope = 'ORGANIZATION' AND deleted_at IS NULL;

CREATE INDEX idx_templates_scope_status ON templates (scope, status, tenant_id, organization_id);
CREATE INDEX idx_templates_tenant_org ON templates (tenant_id, organization_id) WHERE deleted_at IS NULL;
CREATE INDEX idx_templates_category ON templates (category_id) WHERE deleted_at IS NULL;

CREATE TABLE template_versions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  template_id BIGINT NOT NULL REFERENCES templates(id),
  version_number INTEGER NOT NULL CHECK (version_number > 0),
  schema_version INTEGER NOT NULL,
  document_json JSONB NOT NULL,
  theme_json JSONB NOT NULL DEFAULT '{}'::jsonb,
  required_features JSONB NOT NULL DEFAULT '[]'::jsonb,
  preview_asset_id BIGINT,
  checksum TEXT NOT NULL,
  status TEXT NOT NULL CHECK (status IN ('DRAFT','PUBLISHED','ARCHIVED')),
  created_by BIGINT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  published_at TIMESTAMPTZ,
  UNIQUE (template_id, version_number)
);

CREATE INDEX idx_template_versions_template ON template_versions (template_id, status);

ALTER TABLE templates
  ADD CONSTRAINT fk_templates_current_version
  FOREIGN KEY (current_published_version_id) REFERENCES template_versions(id);

-- Published versions are immutable: content can never change, only the status may move to ARCHIVED.
CREATE FUNCTION prevent_published_version_mutation() RETURNS trigger AS $$
BEGIN
  IF OLD.status = 'PUBLISHED' AND (
       NEW.document_json IS DISTINCT FROM OLD.document_json
    OR NEW.theme_json IS DISTINCT FROM OLD.theme_json
    OR NEW.required_features IS DISTINCT FROM OLD.required_features
    OR NEW.checksum IS DISTINCT FROM OLD.checksum
    OR NEW.schema_version IS DISTINCT FROM OLD.schema_version
    OR NEW.version_number IS DISTINCT FROM OLD.version_number
    OR NEW.template_id IS DISTINCT FROM OLD.template_id
    OR NEW.status NOT IN ('PUBLISHED','ARCHIVED')
  ) THEN
    RAISE EXCEPTION 'published template versions are immutable' USING ERRCODE = '23000';
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_template_versions_immutable
  BEFORE UPDATE ON template_versions
  FOR EACH ROW EXECUTE FUNCTION prevent_published_version_mutation();

CREATE TABLE template_tags (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id BIGINT,
  organization_id BIGINT,
  slug TEXT NOT NULL,
  label TEXT NOT NULL
);

CREATE UNIQUE INDEX ux_template_tags_scope_slug
  ON template_tags (COALESCE(tenant_id, 0), COALESCE(organization_id, 0), slug);

-- Tags are catalog metadata of the template (not of an individual version).
CREATE TABLE template_tag_links (
  template_id BIGINT NOT NULL REFERENCES templates(id),
  tag_id BIGINT NOT NULL REFERENCES template_tags(id),
  PRIMARY KEY (template_id, tag_id)
);

CREATE TABLE template_apply_jobs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id BIGINT NOT NULL,
  organization_id BIGINT NOT NULL,
  website_id BIGINT NOT NULL,
  template_id BIGINT NOT NULL REFERENCES templates(id),
  version_id BIGINT NOT NULL REFERENCES template_versions(id),
  status TEXT NOT NULL CHECK (status IN ('QUEUED','RUNNING','SUCCEEDED','FAILED')),
  idempotency_key TEXT NOT NULL,
  request_hash TEXT NOT NULL,
  request_json JSONB NOT NULL DEFAULT '{}'::jsonb,
  result_json JSONB,
  error_code TEXT,
  attempts INTEGER NOT NULL DEFAULT 0,
  created_by BIGINT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (tenant_id, organization_id, idempotency_key)
);

CREATE INDEX idx_apply_jobs_incomplete ON template_apply_jobs (id) WHERE status IN ('QUEUED','RUNNING');

CREATE TABLE idempotency_keys (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id BIGINT NOT NULL,
  organization_id BIGINT NOT NULL,
  operation TEXT NOT NULL,
  idempotency_key TEXT NOT NULL,
  request_hash TEXT NOT NULL,
  response_status INTEGER,
  response_json JSONB,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (tenant_id, organization_id, operation, idempotency_key)
);

CREATE TABLE template_audit_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id BIGINT NOT NULL,
  organization_id BIGINT NOT NULL,
  actor_user_id BIGINT NOT NULL,
  action TEXT NOT NULL,
  resource_type TEXT NOT NULL,
  resource_id TEXT,
  request_id TEXT,
  metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX idx_audit_scope_time ON template_audit_logs (tenant_id, organization_id, created_at);

CREATE TABLE outbox_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id UUID NOT NULL DEFAULT gen_random_uuid() UNIQUE,
  event_type TEXT NOT NULL,
  payload JSONB NOT NULL,
  occurred_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  published_at TIMESTAMPTZ,
  attempts INTEGER NOT NULL DEFAULT 0,
  next_attempt_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  last_error TEXT
);

CREATE INDEX idx_outbox_pending ON outbox_events (next_attempt_at) WHERE published_at IS NULL;
